#!/usr/bin/env bun
/**
 * Fetches MTA subway station platforms from data.ny.gov and writes
 * src/lib/subway/stations.ts. Stations change rarely; rerun by hand when MTA
 * opens or renames one.
 *
 * Usage: bun scripts/fetch-subway-stations.ts
 */

import { writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT = join(__dirname, "../src/lib/subway/stations.ts");
const API =
  "https://data.ny.gov/resource/39hk-dx4f.json?$select=gtfs_stop_id,stop_name,daytime_routes,gtfs_latitude,gtfs_longitude,north_direction_label,south_direction_label&$order=gtfs_stop_id&$limit=1000";

interface Row {
  gtfs_stop_id: string;
  stop_name: string;
  daytime_routes: string;
  gtfs_latitude: string;
  gtfs_longitude: string;
  north_direction_label?: string;
  south_direction_label?: string;
}

const rows = (await fetch(API, { signal: AbortSignal.timeout(30_000) }).then((r) => {
  if (!r.ok) throw new Error(`HTTP ${r.status} ${r.statusText}`);
  return r.json();
})) as Row[];

if (rows.length < 400) {
  console.error(`Expected ~500 stations, got ${rows.length}. Aborting.`);
  process.exit(1);
}

const label = (value: string | undefined) => (value && value !== "Last Stop" ? value.trim() : null);

const stations = rows.map((r) => ({
  id: r.gtfs_stop_id,
  name: r.stop_name,
  latitude: Number(r.gtfs_latitude),
  longitude: Number(r.gtfs_longitude),
  routes: r.daytime_routes.split(" ").filter(Boolean),
  northLabel: label(r.north_direction_label),
  southLabel: label(r.south_direction_label),
}));

const body = `// Generated by scripts/fetch-subway-stations.ts from MTA Subway Stations (data.ny.gov 39hk-dx4f). Do not edit by hand.
import type { SubwayStation } from "./types";

export const SUBWAY_STATIONS: SubwayStation[] = ${JSON.stringify(stations, null, 2)};
`;

writeFileSync(OUTPUT, body);
console.warn(`Wrote ${stations.length} stations to ${OUTPUT}`);
